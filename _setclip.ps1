## 三、为什么做（问题从哪里来）

- **信息太分散**：课表在教务系统，排班在群里，消费在支付账单里，截止日期靠自己记。单独查一件事不难，难的是把它们放在一起看。
- **真正想问的只有三句话**：这周打了多久工、赚了多少？这周花了多少、还剩多少？买一件东西，相当于自己要工作多久？
- **现有记账 App 不认"兼职按小时算钱"这件事**：要么只是流水账，要么一上来就让你建预算、资产、多账本，记三天就放弃了。
- **我的验收标准很土**：记一笔不超过 15 秒；每笔收入、支出和汇总都必须算对；刷新页面不能丢；导出的 CSV 用 Excel 打开不能乱码。

所以第一版只做一件事：**先把"记兼职 + 记支出 + 看周账单"做顺**，日程、专注、校园办事这些功能长在这个骨架上，而不是一上来铺开。

