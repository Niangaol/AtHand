## 二、我的作品是什么（一句话）

**「顺手 AtHand」是一个给在校大学生用的校园个人助手：把兼职排班和日常花销记在同一个地方，打开首页就知道这周打了多久工、赚了多少、花了多少、还剩多少。**

目标用户很具体：有兼职的大学生。典型场景是——周五晚上从奶茶店下班，回宿舍路上花 20 秒把今天 3 小时班记上，顺手记下晚饭，然后看一眼这周净剩多少。

