## 四、怎么用（5 步，照做就能用起来）

1. **打开** https://athand-qnvq63y722x.qoder.zone 。不用注册、不用下载，进来就是"示例模式"，页面上有现成的样例账单。
2. **点左侧「记一笔」→「记工时」**：选兼职单位（默认有"校园奶茶店 / 周末家教"）、填日期和起止时间、时薪，下方会实时算出"3.0 小时，预计收入 ¥60.00"，点「保存记录」。保存后示例账单会自动清掉，只留你的真实记录。
3. **切到「记支出」**：填金额、选一个分类（吃饭 / 交通 / 日用 / 娱乐 / 学习 / 其他），保存。一笔账 15 秒内能记完。
4. **点「周账单」**：看本周兼职收入、生活支出、本周净剩，按天展开明细；可以翻上一周 / 下一周，也可以只看收入或只看支出。
5. **点「设置」**：导出 CSV（Excel 打开不乱码）、清空数据；「单位管理」里先把常用的兼职单位和时薪存好，以后记工时不用重填。

> 数据只保存在你当前浏览器的本地存储里，不上传服务器，也不用担心账号问题。

