## 五、用 Qoder 做出来的过程

先给整体规模：**10 次提交、92 个源文件、31 个测试文件，前端 src 约 7100 行（含测试与样式）**，从需求文档到公网上线集中在 11 月 20—22 日三天。

我的做法是：**先自己把需求写死，再把"实现"整段交给 Qoder，我负责当甲方和验收。**

### 第 1 步：我写需求，Qoder 起骨架

我先写了《顺手-需求文档-通俗精简版》：这个产品给谁、第一版做什么、不做什么、怎样才算做好了。然后把文档交给 Qoder，让它生成 React + Vite + TypeScript 项目、路由和左侧导航（首页 / 今天 / 记一笔 / 周账单 / 单位管理 / 月度汇总 / 设置）。

**我改的**：导航按"学习与节奏 / 钱与时间 / 校园与远方 / 数据与设置"分组；首页只回答"今天要做什么"，不做成堆砌数字的仪表盘。

### 第 2 步：记账闭环交给 Qoder，规则由我定

Qoder 实现工时计算（跨午夜、扣除休息）、六个支出分类、周汇总与按天明细。它一开始给我的是一版"什么都能填"的表单。

**我改的**：
- 表单只留必要字段，备注可选，默认值给好（当天日期、9:00–12:00、上次用的单位），目标是 15 秒记完；
- 跨午夜必须算对，结束时间早于开始时间要能自动按"次日"处理；
- 金额统一两位小数，支出分类只允许六个，不让用户自己加。

### 第 3 步：数据归属，我加边界

账本先落在浏览器本地；Qoder 另外写了本机同步网关（本机运行的 Node 服务，不在公网部署），方便手机浏览器查看电脑上的账本。

**我改的**：同步接口分只读 / 可写两种令牌，只读令牌不能改账；页面上明确写清"数据只保存在当前浏览器 / 本机"，不偷偷上传。

### 第 4 步：功能开始长，我负责砍

在这个骨架上，Qoder 继续写出了专注计时、日程、旅记、校园办事入口、生活服务（MCP）这些页面。

**我砍掉的**：预算与理财建议、账单自动识别、多人协作与社交、多学校适配。理由只有一个——**第一版要让人敢每天打开，而不是功能列表好看**。

### 第 5 步：部署与复验（Qoder Sites）

用 Qoder 的 Sites 能力打包 dist/、发布，并把访问策略设为**公开访问**；发布后我用**未登录的浏览器**重新打开验证：首页 200、静态资源 200、没有登录跳转。

**我验的**：首页、记一笔、周账单三条主路径逐页点过；刷新后记录仍在；示例账单在第一次真实记录后自动清掉。

### 我到底改了什么（一句话）

> **Qoder 负责"快"，我负责"不对"。** 需求边界、字段取舍、计算规则、数据边界、验收清单都是我定的；Qoder 负责把每一条变成能跑的代码。

