import { test, expect } from '@playwright/test';

test('travel plans, independent packing and confirmed map visits work on mobile', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 });
  await page.goto('/trips');
  await page.getByRole('button', { name: '新建旅行' }).click();
  await page.getByLabel('旅行名称').fill('杭州周末');
  await page.getByLabel('出发日期').fill('2026-11-01');
  await page.getByLabel('结束日期').fill('2026-11-03');
  await page.getByRole('button', { name: '保存旅行' }).click();
  await page.getByRole('link', { name: '杭州周末', exact: true }).click();
  await page.getByLabel('2026-11-01攻略', { exact: true }).fill('西湖走走');
  await page.getByRole('button', { name: '添加2026-11-01攻略' }).click();
  await expect(page.getByRole('region', { name: '2026-11-01行程' })).toContainText('西湖走走');
  await page.getByLabel('2026-11-02攻略', { exact: true }).fill('灵隐寺');
  await page.getByRole('button', { name: '添加2026-11-02攻略' }).click();
  await expect(page.getByRole('region', { name: '2026-11-02行程' })).toContainText('灵隐寺');
  await page.getByLabel('行李物品').fill('充电器');
  await page.getByRole('button', { name: '添加行李' }).click();
  await page.getByRole('checkbox', { name: '充电器' }).click();
  await expect(page.getByRole('checkbox', { name: '充电器' })).toBeChecked();
  await page.getByLabel('选择城市').selectOption('cn:hangzhou');
  await page.getByLabel('到访日期').fill('2026-11-02');
  await page.getByRole('checkbox', { name: '确认已到访' }).check();
  await page.getByRole('button', { name: '保存城市记录' }).click();
  await expect(page.getByRole('region', { name: '本次城市记录' })).toContainText('杭州');
  await page.reload();
  await expect(page.getByRole('checkbox', { name: '充电器' })).toBeChecked();
  await page.getByRole('link', { name: '返回旅记' }).click();
  await page.getByRole('button', { name: '地图上的杭州', exact: true }).click();
  await expect(page.getByRole('region', { name: '城市详情' })).toContainText('到访 1 次');
  await page.context().setOffline(true);
  await page.getByRole('button', { name: '放大地图' }).click();
  await expect(page.getByRole('group', { name: '离线世界城市足迹地图' })).toBeVisible();
  await page.evaluate(() => { (document.activeElement as HTMLElement)?.blur(); window.scrollTo({ top: 0, behavior: 'instant' }); });
  await page.screenshot({ path: 'test-results/trips-mobile.png', fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: 'test-results/trips-desktop.png', fullPage: true });
  await page.context().setOffline(false);
  await page.setViewportSize({ width: 375, height: 812 });
  await page.getByRole('button', { name: '新建旅行' }).click();
  await page.getByLabel('旅行名称').fill('上海三日');
  await page.getByLabel('出发日期').fill('2026-11-10');
  await page.getByLabel('结束日期').fill('2026-11-12');
  await page.getByRole('button', { name: '保存旅行' }).click();
  await page.getByRole('link', { name: '上海三日', exact: true }).click();
  await page.getByLabel('清单来源').selectOption({ label: '杭州周末' });
  await page.getByRole('button', { name: '复制这份行李清单' }).click();
  await expect(page.getByText('复制自：杭州周末', { exact: true })).toBeVisible();
  await expect(page.getByRole('checkbox', { name: '充电器' })).not.toBeChecked();
  await page.getByRole('link', { name: '返回旅记' }).click();
  await page.getByRole('link', { name: '杭州周末', exact: true }).click();
  await expect(page.getByRole('checkbox', { name: '充电器' })).toBeChecked();
  await page.getByRole('button', { name: '编辑旅行' }).click();
  await page.getByLabel('出发日期').fill('2026-11-02');
  await page.getByRole('button', { name: '保存旅行' }).click();
  await expect(page.getByRole('alert')).toContainText('范围外');
  await page.getByRole('button', { name: '取消', exact: true }).click();
  await page.getByRole('button', { name: '删除旅行' }).click();
  await page.getByRole('button', { name: '确认删除' }).click();
  await expect(page.getByRole('button', { name: '地图上的杭州', exact: true })).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
